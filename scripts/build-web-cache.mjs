import { readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export function serviceWorkerSource(files, revision) {
  return `// Generated by scripts/build-web-cache.mjs. No user documents or model requests are cached here.
const SCOPE=new URL(self.registration.scope).pathname;
// Encoded paths cannot contain the ':' delimiter, including nested '-name/' scopes.
const PREFIX='doc2audio-shell:'+encodeURIComponent(SCOPE)+':';
const LEGACY_PREFIX='doc2audio-shell-'+SCOPE+'-';
const CACHE=PREFIX+'${revision}';
const FILES=${JSON.stringify(files)};
self.addEventListener('install',event=>event.waitUntil((async()=>{
 const existed=(await caches.keys()).includes(CACHE);
 const cache=await caches.open(CACHE);
 // The same immutable asset revision may already be serving open tabs.
 // Reuse a complete cache without refetching or modifying its responses.
 if(existed && (await Promise.all(FILES.map(p=>cache.match(new URL(p,self.registration.scope))))).every(Boolean)) return;
 try {
  // Bound simultaneous transfers of large WASM resources.
  for(let i=0;i<FILES.length;i+=4) await cache.addAll(FILES.slice(i,i+4).map(p=>new Request(new URL(p,self.registration.scope),{cache:'reload'})));
 } catch(error) {
  // Failed installs never activate. Remove only the cache this attempt created;
  // an already-existing cache can still be serving the current active worker.
  if(!existed) await caches.delete(CACHE);
  throw error;
 }
})()));
self.addEventListener('activate',event=>event.waitUntil((async()=>{
 for(const name of await caches.keys()) {
  // Previous builds used a raw pathname followed by a 16-digit revision.
  // A startsWith check alone would also match another app's nested scope.
  const legacy=name.startsWith(LEGACY_PREFIX)&&/^[0-9a-f]{16}$/.test(name.slice(LEGACY_PREFIX.length));
  if((name.startsWith(PREFIX)||legacy)&&name!==CACHE) await caches.delete(name);
 }
 await self.clients.claim();
 for(const client of await self.clients.matchAll()) client.postMessage({type:'offline-ready'});
})()));
self.addEventListener('fetch',event=>{
 const url=new URL(event.request.url),scope=new URL(self.registration.scope);
 if(event.request.method!=='GET'||url.origin!==scope.origin||!url.pathname.startsWith(scope.pathname))return;
 const path=url.pathname.slice(scope.pathname.length);
 if(path.startsWith('api/'))return;
 if(event.request.mode==='navigate') event.respondWith(caches.open(CACHE).then(cache=>cache.match(new URL('index.html',scope)).then(hit=>hit||fetch(event.request))));
 else if(FILES.includes(path)) event.respondWith(caches.open(CACHE).then(cache=>cache.match(new URL(path,scope)).then(hit=>hit||fetch(event.request))));
});
`;
}

export async function buildWebCache(dist = resolve(root, 'apps/web/dist')) {
  const files = [];
  const hash = createHash('sha256');
  async function scan(dir) {
    const entries = await readdir(dir, { withFileTypes: true });
    entries.sort((a, b) => a.name.localeCompare(b.name));
    for (const item of entries) {
      const path = resolve(dir, item.name);
      if (item.isDirectory()) await scan(path);
      else if (item.name !== 'sw.js') {
        const name = relative(dist, path).split('\\').join('/');
        files.push(name);
        hash.update(name);
        hash.update(await readFile(path));
      }
    }
  }
  await scan(dist);
  files.sort();
  const revision = hash.digest('hex').slice(0, 16);
  await writeFile(resolve(dist, 'sw.js'), serviceWorkerSource(files, revision));
  console.log(`오프라인 웹 캐시: ${files.length} files, revision ${revision}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildWebCache();
}
